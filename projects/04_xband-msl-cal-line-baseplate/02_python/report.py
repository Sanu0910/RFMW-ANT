"""Design report (markdown), BOM and hole table (CSV) -> ../05_docs/"""
import os, csv
import config as C

OUTD = os.path.join(C.ROOT, "05_docs")


def _holes(B, H):
    K = C.CONN; ox, oy = -H.x0, H.yo; rows = []
    for i, (x, y, _d) in enumerate(B["holes"]):
        rows.append(("A%d" % (i + 1), "M3-6H THRU", x + ox, y + oy, H.z_floor, "pocket floor, -Z"))
    for j, p in enumerate(H.ports):
        f = "%s face %sX" % (p["label"], "-" if p["ux"] < 0 else "+")
        rows.append(("B%d" % (j + 1), "D%.2f +0.05/0 THRU wall" % K["bore_d"], p["xf"] + ox, oy, H.pin_z, f))
        for k, (_hx, hy, hz) in enumerate(p["holes"]):
            rows.append(("C%d" % (4 * j + k + 1), "M2.5-6H depth %.1f" % K["tap_depth"], p["xf"] + ox, hy + oy, hz, f))
    return rows


def write(done):
    os.makedirs(OUTD, exist_ok=True)
    P, K, T = C.PLATE, C.CONN, C.PCB
    L = ["# X-band MSL cal-line base plates: design report", "",
         "_Generated by `02_python/build_all.py` from `config.py`; do not edit by hand._", "",
         "## What it is",
         "An open, lightweight machined base plate for each X-band THRU cal board in `00_input/MSL_SL_Cal_Lines.zip` "
         "(RO4350B 30 mil, MSL launch -> via -> stripline -> via -> MSL). Two connector walls carry the same "
         "%s used on the project 01 divider housing; the board drops into a locating pocket and is held by its own 4 x M3 holes." % K["part"], "",
         "## Plates", "", "| Part | Board | Plate L x W x H | Mass (6061) | Underside pockets |", "|---|---|---|---|---|"]
    for k, (B, H, _r) in done.items():
        L.append("| %s | %s | %.2f x %.2f x %.2f | %.1f g | %d |" % (B["pn"], B["name"], H.L, H.W, H.z_wall, getattr(H, "mass_g", 0), len(H.under)))
    B0, H0, _ = next(iter(done.values()))
    L += ["", "## Heights (both plates, Z from the plate bottom)", "",
          "| Item | Z | How it is set |", "|---|---|---|",
          "| Connector flange bottom | %.2f | flange margin above the bench |" % (H0.pin_z - K["flange"] / 2),
          "| Pocket floor (datum A) | %.2f | axis - pin radius - board t |" % H0.z_floor,
          "| Plate top / rim | %.2f | floor + %.1f locating pocket |" % (H0.z_top, P["pocket"]),
          "| PCB top | %.2f | floor + t %.2f [ASSUMED] |" % (H0.z_pcb_top, T["t"]),
          "| Connector axis (B1, B2) | %.2f | pin bottom on the trace |" % H0.pin_z,
          "| Wall top | %.2f | flange top + %.2f |" % (H0.z_wall, P["wall_above_flange"]),
          "| Underside pocket roof | %.2f | %.1f mm skin under the floor |" % (H0.z_under, P["skin"]), "",
          "## Checks", "", "| Check | Value | Rule | Result |", "|---|---|---|---|"]
    for name, val, rule, ok in H0.checks():
        L.append("| %s | %s | %s | %s |" % (name, val, rule, "PASS" if ok else "FAIL"))
    L += ["", "## Assumptions", "",
          "| Value | Used | How to settle |", "|---|---|---|",
          "| Cal PCB thickness | %.2f mm (2 x 0.762 RO4350B + 0.102 bond ply + 3 x 35 um Cu) | The DXFs give no stack-up. Get the fab's finished thickness; change `PCB['t']` and rebuild (bore axis = floor + t + %.2f). |" % (T["t"], K["pin_d"] / 2),
          "| PCB bottom is solid ground (L3) | yes | Matches BOTTOM_GROUND in the DXF; the plate is the RF return path from the connector body. |",
          "| Board outline tolerance | +/-0.1 | Pocket is board + %.2f (ends) / + %.2f (sides). |" % (P["clr_x"], P["clr_y"]), "",
          "## Notes",
          "- The pocket ends are the connector walls: the 5.09 mm spigot stands 0.09 proud of the 5.0 wall, leaving %.2f mm to the board end, "
          "and the 2.92 mm pin then covers %.2f mm of launch copper." % (P["clr_x"] - (K["spigot_len"] - P["wall"]), float(H0.checks()[3][1])),
          "- The plate is open (no lid). The stripline section is shielded by the board's via fence; the MSL launches radiate a little, "
          "which is part of what the THRU calibrates.",
          "- Underside lightening keeps a %.1f mm rib on the line axis, %.1f mm side rims and R%.1f bosses round the M3 taps; "
          "the wall zones stay solid for the M2.5 flange taps." % (P["rib"], P["under_rim"], P["boss_r"]), ""]
    with open(os.path.join(OUTD, "CRL-XB-CALP_design_report.md"), "w", encoding="utf-8") as fh: fh.write("\n".join(L))
    with open(os.path.join(OUTD, "CRL-XB-CALP_BOM.csv"), "w", newline="") as fh:
        w = csv.writer(fh); w.writerow(["Assembly", "Item", "Qty", "Part", "Description", "Source"])
        for k, (B, H, _r) in done.items():
            for row in ((1, 1, B["pn"] + "_PLATE", "Base plate, " + P["material"], "CNC, drawing " + B["pn"] + "-DWG"),
                        (2, 1, B["name"], "Cal PCB THRU %s mm" % k, "customer DXF"),
                        (3, 2, "23_SMA-50-0-272/133_N", K["part"], "HUBER+SUHNER item 23030310"),
                        (4, 8, "ISO 4762 M2.5x5 A2-70", "flange screws", "stock"),
                        (5, 4, "ISO 4762 M3x%g A2-70" % P["m3_screw_len"], "PCB screws", "stock")):
                w.writerow([B["pn"] + "_ASSY"] + list(row))
    with open(os.path.join(OUTD, "CRL-XB-CALP_HOLE_TABLE.csv"), "w", newline="") as fh:
        w = csv.writer(fh); w.writerow(["Part", "ID", "Feature", "X", "Y", "Z", "Face"])
        for k, (B, H, _r) in done.items():
            for r in _holes(B, H): w.writerow([B["pn"], r[0], r[1], "%.3f" % r[2], "%.3f" % r[3], "%.3f" % r[4], r[5]])
    print("report -> 05_docs")
