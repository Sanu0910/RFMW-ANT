"""Emit 06_firmware/board_pins.h (ESP32-S3 GPIO map) straight from the design netlist."""
import os, re
import design as D

HERE = os.path.dirname(os.path.abspath(__file__))
esp = D.by_ref()["U8"]
# WROOM-1 module pin -> GPIO (KiCad symbol pin names)
from libsym import get_symbol, pins
names = {p[0]: p[1] for p in pins(get_symbol("RF_Module:ESP32-S3-WROOM-1"))}
rows = []
for pin, net in esp["nets"].items():
    nm = names[pin]
    m = re.match(r"IO(\d+)$", nm)
    gpio = int(m.group(1)) if m else {"RXD0": 44, "TXD0": 43, "USB_D-": 19, "USB_D+": 20}.get(nm)
    if gpio is None or net in ("GND", "+3V3"):
        continue
    rows.append((gpio, net))
rows.sort()
out = ["/* Auto-generated by 02_python/make_pins.py from design.py - do not edit. */",
       "/* CRL-TRK-2W-01 rev A0 - ESP32-S3-WROOM-1-N8R2 GPIO map */", "#pragma once", ""]
for g, n in rows:
    macro = "PIN_" + re.sub(r"[^A-Z0-9]", "_", n.upper()).strip("_")
    out.append(f"#define {macro:<26} {g:>2}   /* {n} */")
out += ["", "/* I2C addresses */", "#define I2C_ADDR_IMU        0x68   /* IIM-42652, AD0 = GND */",
        "#define I2C_ADDR_GAUGE      0x0B   /* LC709203F */", "#define I2C_ADDR_RTC        0x52   /* RV-3028-C7 */", "",
        "/* ADC scaling (ADC1, 12 dB attenuation) */",
        "#define VIN_DIV             ((1000.0f + 68.0f) / 68.0f)   /* R7/R8 */",
        "#define VBAT_DIV            2.0f                           /* R15/R16 */",
        "#define AIN1_DIV            ((100.0f + 10.0f) / 10.0f)    /* R47/R48 */",
        "#define IGN_DIV             ((100.0f + 22.0f) / 22.0f)    /* R41/R42 */", "",
        "/* Active levels */", "#define PANIC_ACTIVE_LEVEL  0", "#define IGN_ACTIVE_LEVEL    1",
        "#define MDM_PWRKEY_PULSE_MS 1100   /* SIM7080G power-on: PWRKEY low >= 1 s */",
        "#define LED_STAT_ON         1", ""]
p = os.path.join(HERE, "..", "06_firmware", "board_pins.h")
open(p, "w").write("\n".join(out))
print("\n".join(out[4:4 + len(rows)]))
