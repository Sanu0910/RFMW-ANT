"""Emit 06_firmware/board_pins.h (EC200U QuecOpen pin map) straight from the design netlist."""
import os, re
import design as D
from make_lib import EC200U

HERE = os.path.dirname(os.path.abspath(__file__))
GPIO = {"27": 1, "26": 2, "24": 3, "25": 4}          # QuecPython machine.Pin.GPIOn <- module pin
u3 = D.by_ref()["U3"]["nets"]
out = ["/* Auto-generated by 02_python/make_pins.py from design.py - do not edit. */",
       f"/* {D.PN} rev {D.REV} - Quectel EC200U-CN (QuecOpen / QuecPython) pin map. VERIFY against the EC200U HD. */",
       "#pragma once", "", "/* module pin number, QuecOpen GPIO number */"]
for pin, g in GPIO.items():
    net = u3[pin]
    out.append(f"#define {'PIN_' + re.sub(r'[^A-Z0-9]', '_', net):<22} {g:>2}   /* GPIO{g} = module pin {pin} ({EC200U[int(pin)][0]}) */")
out += ["", "/* fixed-function pins */"]
for pin in ("41", "42", "44", "45", "67", "68", "61", "6", "21", "20"):
    out.append(f"/* pin {pin:>2} {EC200U[int(pin)][0]:<11} -> {u3[pin]} */")
out += ["", "#define GNSS_UART           0      /* MAIN UART (pins 67/68), NMEA 9600 8N1 from L76K */",
        "#define I2C_ADDR_ACC        0x18   /* LIS3DH, SA0 = GND */",
        "#define ADC_VIN_CH          1      /* ADC1 */",
        "#define ADC_VBAT_CH         0      /* ADC0 */",
        "#define VIN_DIV             ((1000.0f + 33.0f) / 33.0f)   /* R5/R6 */",
        "#define VBAT_DIV            ((300.0f + 100.0f) / 100.0f)  /* R7/R8 */",
        "#define IGN_ACTIVE_LEVEL    0      /* IGN_DET_N low = ignition on */",
        "#define RELAY_ACTIVE_LEVEL  1",
        "#define GNSS_EN_ACTIVE      1", ""]
p = os.path.join(HERE, "..", "06_firmware", "board_pins.h")
open(p, "w").write("\n".join(out))
print("\n".join(out))
