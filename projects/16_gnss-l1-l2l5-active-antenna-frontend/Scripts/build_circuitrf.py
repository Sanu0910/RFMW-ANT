"""Write the circuitRF netlist of the front end and run it with the circuitRF CLI (cross-check #2).

Output: ../circuitRF/gnss_frontend.cnl, ../circuitRF/gnss_frontend_circuitRF.s3p and
../Extracted_Data/crosscheck_circuitrf.json (difference to the scikit-rf result).
circuitRF executable: env CIRCUITRF_EXE, else %LOCALAPPDATA%/circuitRF-1.6.1/x/circuitRF.exe.
"""
import json
import os
import subprocess
from pathlib import Path

import numpy as np
import skrf as rf

import models as M

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "circuitRF"
OUT.mkdir(exist_ok=True)
EXE = os.environ.get("CIRCUITRF_EXE", str(Path(os.environ.get("LOCALAPPDATA", "")) / "circuitRF-1.6.1/x/circuitRF.exe"))
B = M.BIAS
RQ = 2 * np.pi * 1.4e9 * B["l_choke"] / B["l_choke_q"]


def lna_stage(tag, n_in, n_out):
    return f"""; LNA stage {tag}: DC block -> TQP3M9037 -> bias tee -> DC block (Qorvo eval values)
C:C1_{tag}  {n_in}  {tag}_c1  C={B['c_block'] * 1e12:g} pF
L:ESL1_{tag}  {tag}_c1  {tag}_c1b  L={B['c_block_esl'] * 1e9:g} nH
R:ESR1_{tag}  {tag}_c1b  {tag}_in  R={B['c_block_esr']:g} Ohm
SnP:U_{tag}  {tag}_in  {tag}_out  NumPorts=2  File="../Touchstone/TQP3M9037_5V.s2p"
L:LCHK_{tag}  {tag}_out  {tag}_l1  L={B['l_choke'] * 1e9:g} nH
R:RCHK_{tag}  {tag}_l1  {tag}_vdd  R={RQ:.4f} Ohm
C:CPAR_{tag}  {tag}_out  {tag}_vdd  C={B['l_choke_cpar'] * 1e12:g} pF
C:C3_{tag}  {tag}_vdd  {tag}_c3  C={B['c_bypass'] * 1e12:g} pF
L:ESL3_{tag}  {tag}_c3  {tag}_c3b  L={B['c_bypass_esl'] * 1e9:g} nH
R:ESR3_{tag}  {tag}_c3b  0  R=0.1 Ohm
C:C2_{tag}  {tag}_out  {tag}_c2  C={B['c_block'] * 1e12:g} pF
L:ESL2_{tag}  {tag}_c2  {tag}_c2b  L={B['c_block_esl'] * 1e9:g} nH
R:ESR2_{tag}  {tag}_c2b  {n_out}  R={B['c_block_esr']:g} Ohm
"""


def branch(tag, port_net, saw_file, num):
    return f"""; ===== {tag} branch =====
SnP:CP_{tag}  {port_net}  {tag}_lhcp  {tag}_fa  {tag}_fb  NumPorts=4  File="../Touchstone/PatchCP_ideal_RHCP_feed.s4p"
R:RLHCP_{tag}  {tag}_lhcp  0  R=50 Ohm
SnP:HYB_{tag}  {tag}_h1  {tag}_h2  {tag}_fa  {tag}_fb  NumPorts=4  File="../Touchstone/HC125A.s4p"
R:RISO_{tag}  {tag}_h2  0  R=50 Ohm
{lna_stage(tag + "A", tag + "_h1", tag + "_s1i")}SnP:SAW1_{tag}  {tag}_s1i  {tag}_s1o  NumPorts=2  File="../Touchstone/{saw_file}"
{lna_stage(tag + "B", tag + "_s1o", tag + "_s2i")}SnP:SAW2_{tag}  {tag}_s2i  {tag}_out  NumPorts=2  File="../Touchstone/{saw_file}"
"""


def main():
    cnl = f"""; gnss_frontend.cnl - Project 16 GNSS L1 + L2/L5 active antenna front end
; generated by Scripts/build_circuitrf.py; run: circuitRF sparam gnss_frontend.cnl
; ports: 1 = L1 virtual RHCP input, 2 = L2/L5 virtual RHCP input, 3 = RF output (to receiver)
Term:P1  in_l1  0  Num=1  Z=50
Term:P2  in_l2  0  Num=2  Z=50
Term:P3  rf_out  0  Num=3  Z=50
{branch("L1", "in_l1", "B7504.s2p", 1)}
{branch("L2", "in_l2", "B8889_matched.s2p", 2)}
; ===== combiner =====
SnP:DXP  rf_out  L1_out  L2_out  NumPorts=3  File="../Touchstone/DXP02A.s3p"

analysis SP1 type=sparam start=0.6 stop=2.2 npts=3201 Unit=GHz
"""
    (OUT / "gnss_frontend.cnl").write_text(cnl)
    chk = subprocess.run([EXE, "check", "gnss_frontend.cnl"], cwd=OUT, capture_output=True, text=True)
    print(chk.stdout.strip()[-300:], chk.stderr.strip()[-300:])
    run = subprocess.run([EXE, "sparam", "gnss_frontend.cnl", "-o", "gnss_frontend_circuitRF.s3p"],
                         cwd=OUT, capture_output=True, text=True)
    print(run.stdout.strip()[-400:], run.stderr.strip()[-400:])
    crf = rf.Network(str(OUT / "gnss_frontend_circuitRF.s3p"))
    ref = rf.Network(str(ROOT / "Touchstone" / "SIM_System_3port.s3p")).interpolate(crf.frequency)
    f = crf.f
    inband = ((f > 1.164e9) & (f < 1.230e9)) | ((f > 1.559e9) & (f < 1.606e9))
    rep = {}
    for nm, (i, j) in {"S31": (2, 0), "S32": (2, 1), "S11": (0, 0), "S22": (1, 1), "S33": (2, 2)}.items():
        d = 20 * np.log10(abs(crf.s[:, i, j])) - 20 * np.log10(abs(ref.s[:, i, j]))
        rep[nm] = dict(max_abs_diff_db_inband=float(abs(d[inband]).max()))
        print(nm, rep[nm])
    (ROOT / "Extracted_Data" / "crosscheck_circuitrf.json").write_text(json.dumps(rep, indent=1))


if __name__ == "__main__":
    main()
