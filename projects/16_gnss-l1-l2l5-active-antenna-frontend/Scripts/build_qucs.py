"""Write the Qucsator-RF netlist of the front end and run it with Qucs-S's qucsator_rf (cross-check #3).

Output: ../QucsS/gnss_frontend.net, ../QucsS/gnss_frontend_qucs.s3p and
../Extracted_Data/crosscheck_qucs.json (difference to the scikit-rf result).
Qucs-S bin folder: env QUCS_BIN, else C:/Program Files/Qucs-S/bin.
"""
import json
import os
import subprocess
from pathlib import Path

import numpy as np
import skrf as rf

import models as M

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "QucsS"
OUT.mkdir(exist_ok=True)
BIN = Path(os.environ.get("QUCS_BIN", "C:/Program Files/Qucs-S/bin"))
TS = (ROOT / "Touchstone").as_posix()
B = M.BIAS
RQ = 2 * np.pi * 1.4e9 * B["l_choke"] / B["l_choke_q"]


def snp(name, nodes, file):
    # polar + cubic matches the scikit-rf reference; rectangular + linear differs by up to 0.07 dB in band
    # because the TQP3M9037 file has only 27 points (0.05-5 GHz)
    return f'SPfile:{name} {" ".join(nodes)} gnd File="{{{TS}/{file}}}" Data="polar" Interpolator="cubic" duringDC="open"\n'


def lna_stage(tag, n_in, n_out):
    return f"""# LNA stage {tag}: DC block -> TQP3M9037 -> bias tee -> DC block (Qorvo eval values)
C:C1_{tag} {n_in} {tag}_c1 C="{B['c_block'] * 1e12:g} pF"
L:ESL1_{tag} {tag}_c1 {tag}_c1b L="{B['c_block_esl'] * 1e9:g} nH"
R:ESR1_{tag} {tag}_c1b {tag}_in R="{B['c_block_esr']:g} Ohm"
{snp("U_" + tag, [tag + "_in", tag + "_out"], "TQP3M9037_5V.s2p")}L:LCHK_{tag} {tag}_out {tag}_l1 L="{B['l_choke'] * 1e9:g} nH"
R:RCHK_{tag} {tag}_l1 {tag}_vdd R="{RQ:.4f} Ohm"
C:CPAR_{tag} {tag}_out {tag}_vdd C="{B['l_choke_cpar'] * 1e12:g} pF"
C:C3_{tag} {tag}_vdd {tag}_c3 C="{B['c_bypass'] * 1e12:g} pF"
L:ESL3_{tag} {tag}_c3 {tag}_c3b L="{B['c_bypass_esl'] * 1e9:g} nH"
R:ESR3_{tag} {tag}_c3b gnd R="0.1 Ohm"
C:C2_{tag} {tag}_out {tag}_c2 C="{B['c_block'] * 1e12:g} pF"
L:ESL2_{tag} {tag}_c2 {tag}_c2b L="{B['c_block_esl'] * 1e9:g} nH"
R:ESR2_{tag} {tag}_c2b {n_out} R="{B['c_block_esr']:g} Ohm"
"""


def branch(tag, port_net, saw_file):
    return (f"# ===== {tag} branch =====\n"
            + snp("CP_" + tag, [port_net, tag + "_lhcp", tag + "_fa", tag + "_fb"], "PatchCP_ideal_RHCP_feed.s4p")
            + f'R:RLHCP_{tag} {tag}_lhcp gnd R="50 Ohm"\n'
            + snp("HYB_" + tag, [tag + "_h1", tag + "_h2", tag + "_fa", tag + "_fb"], "HC125A.s4p")
            + f'R:RISO_{tag} {tag}_h2 gnd R="50 Ohm"\n'
            + lna_stage(tag + "A", tag + "_h1", tag + "_s1i")
            + snp("SAW1_" + tag, [tag + "_s1i", tag + "_s1o"], saw_file)
            + lna_stage(tag + "B", tag + "_s1o", tag + "_s2i")
            + snp("SAW2_" + tag, [tag + "_s2i", tag + "_out"], saw_file))


def main():
    net = f"""# gnss_frontend.net - Project 16 GNSS L1 + L2/L5 active antenna front end (Qucsator-RF netlist)
# generated by Scripts/build_qucs.py; run: qucsator_rf -i gnss_frontend.net -o gnss_frontend.dat
# ports: 1 = L1 virtual RHCP input, 2 = L2/L5 virtual RHCP input, 3 = RF output (to receiver)
Pac:P1 in_l1 gnd Num="1" Z="50 Ohm" P="0 dBm" f="1.5 GHz"
Pac:P2 in_l2 gnd Num="2" Z="50 Ohm" P="0 dBm" f="1.5 GHz"
Pac:P3 rf_out gnd Num="3" Z="50 Ohm" P="0 dBm" f="1.5 GHz"
{branch("L1", "in_l1", "B7504.s2p")}
{branch("L2", "in_l2", "B8889_matched.s2p")}
# ===== combiner =====
{snp("DXP", ["rf_out", "L1_out", "L2_out"], "DXP02A.s3p")}
.SP:SP1 Type="lin" Start="0.6 GHz" Stop="2.2 GHz" Points="3201" Noise="no" NoiseIP="1" NoiseOP="3" saveCVs="no" saveAll="no"
"""
    (OUT / "gnss_frontend.net").write_text(net)
    run = subprocess.run([str(BIN / "qucsator_rf"), "-i", "gnss_frontend.net", "-o", "gnss_frontend.dat"],
                         cwd=OUT, capture_output=True, text=True)
    print(run.stdout.strip()[-400:], run.stderr.strip()[-400:])
    conv = subprocess.run([str(BIN / "qucsconv_rf"), "-if", "qucsdata", "-of", "touchstone",
                           "-i", "gnss_frontend.dat", "-o", "gnss_frontend_qucs.s3p"],
                          cwd=OUT, capture_output=True, text=True)
    print(conv.stdout.strip()[-300:], conv.stderr.strip()[-300:])
    (OUT / "gnss_frontend.dat").unlink(missing_ok=True)   # raw solver output, regenerated on every run
    q = rf.Network(str(OUT / "gnss_frontend_qucs.s3p"))
    ref = rf.Network(str(ROOT / "Touchstone" / "SIM_System_3port.s3p")).interpolate(q.frequency)
    f = q.f
    inband = ((f > 1.164e9) & (f < 1.230e9)) | ((f > 1.559e9) & (f < 1.606e9))
    rep = {}
    for nm, (i, j) in {"S31": (2, 0), "S32": (2, 1), "S11": (0, 0), "S22": (1, 1), "S33": (2, 2)}.items():
        d = 20 * np.log10(abs(q.s[:, i, j])) - 20 * np.log10(abs(ref.s[:, i, j]))
        rep[nm] = dict(max_abs_diff_db_inband=float(abs(d[inband]).max()))
        print(nm, rep[nm])
    (ROOT / "Extracted_Data" / "crosscheck_qucs.json").write_text(json.dumps(rep, indent=1))


if __name__ == "__main__":
    main()
