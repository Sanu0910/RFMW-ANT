INTERFERERS = [  # name, f MHz, level at the antenna feed [ASSUMED]
    ("LTE B13/B14 UL", 787.0, -10.0), ("GSM-900 / LTE B8 UL", 897.5, -10.0),
    ("DME/TACAN (aviation)", 1150.0, -30.0), ("ARNS radar", 1260.0, -40.0),
    ("Inmarsat L-band DL", 1545.0, -80.0), ("Iridium", 1621.0, -20.0),
    ("Inmarsat UL", 1643.0, -20.0), ("LTE B3 UL", 1747.5, -10.0), ("DCS-1800 DL", 1842.5, -30.0),
    ("LTE B1 UL", 1950.0, -10.0),
]


def interferer_table():
    hyb = cp_hybrid_2port()
    rows = []
    for name, f, p in INTERFERERS:
        k = idx(f)
        for branch, saw in (("L1", b7("s")), ("L2/L5", b8("s"))):
            dxr = dxp_2port(1 if branch == "L1" else 2)
            lv = p + db(hyb.s[k, 1, 0])
            lna_in = lv
            lv += db(STAGE.s[k, 1, 0]); lna1_out = lv
            lv += db(saw.s[k, 1, 0]); saw1_out = lv
            lv += db(STAGE.s[k, 1, 0]); lna2_out = lv
            lv += db(saw.s[k, 1, 0]); saw2_out = lv
            lv += db(dxr.s[k, 1, 0])
            _, op1 = lna_large_signal(f)
            rows.append(dict(interferer=name, f_mhz=f, p_ant_dbm=p, branch=branch,
                             lna1_in=float(lna_in), lna1_out=float(lna1_out), saw1_out=float(saw1_out),
                             lna2_out=float(lna2_out), saw2_out=float(saw2_out), rf_out=float(lv),
                             lna1_backoff_db=float(op1 - lna1_out), lna2_backoff_db=float(op1 - lna2_out)))
    return rows


