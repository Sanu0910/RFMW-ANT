def branch_parts(tag, saw_fn):
    cp = M.patch_cp_feed(F); cp.name = f"CP_{tag}"
    hc = on_sys(HC_full, f"HC125A_{tag}")
    st1 = STAGE.copy(); st1.name = f"LNA1_{tag}"
    st2 = STAGE.copy(); st2.name = f"LNA2_{tag}"
    f1, f2 = saw_fn(f"SAW1_{tag}"), saw_fn(f"SAW2_{tag}")
    lhcp = M.load_z(F, name=f"LHCP_{tag}")
    iso = M.load_z(F, name=f"ISO_{tag}")
    return cp, hc, st1, st2, f1, f2, lhcp, iso


def branch_connections(tag, parts, port_in):
    cp, hc, st1, st2, f1, f2, lhcp, iso = parts
    return [
        [(port_in, 0), (cp, 0)], [(cp, 1), (lhcp, 0)],
        [(cp, 2), (hc, 2)], [(cp, 3), (hc, 3)], [(hc, 1), (iso, 0)],
        [(hc, 0), (st1, 0)], [(st1, 1), (f1, 0)], [(f1, 1), (st2, 0)], [(st2, 1), (f2, 0)],
    ]


def build_system():
    p1 = rf.circuit.Circuit.Port(F, "P1_L1_RHCP")
    p2 = rf.circuit.Circuit.Port(F, "P2_L2L5_RHCP")
    p3 = rf.circuit.Circuit.Port(F, "P3_RF_OUT")
    a = branch_parts("L1", b7)
    b = branch_parts("L2", b8)
    dx = on_sys(DX_full, "DXP02A")
    cnx = branch_connections("L1", a, p1) + branch_connections("L2", b, p2) + [
        [(a[5], 1), (dx, 1)], [(b[5], 1), (dx, 2)], [(dx, 0), (p3, 0)]]
    return rf.circuit.Circuit(cnx).network


def cp_hybrid_2port():
    """Virtual RHCP port -> HC125A pin 1 (LHCP and pin 2 terminated in 50 ohm)."""
    pi = rf.circuit.Circuit.Port(F, "in")
    po = rf.circuit.Circuit.Port(F, "out")
    cp = M.patch_cp_feed(F); cp.name = "CP"
    hc = on_sys(HC_full, "HC")
    l1, l2 = M.load_z(F, name="lh"), M.load_z(F, name="iso")
    cnx = [[(pi, 0), (cp, 0)], [(cp, 1), (l1, 0)], [(cp, 2), (hc, 2)], [(cp, 3), (hc, 3)],
           [(hc, 1), (l2, 0)], [(hc, 0), (po, 0)]]
    return rf.circuit.Circuit(cnx).network


def dxp_2port(port):
    """DXP from branch port (1 = L1, 2 = L2/L5) to common, other branch port terminated."""
    dx = on_sys(DX_full, "DX")
    other = 2 if port == 1 else 1
    pi = rf.circuit.Circuit.Port(F, "in")
    po = rf.circuit.Circuit.Port(F, "out")
    ld = M.load_z(F, name="term")
    cnx = [[(pi, 0), (dx, port)], [(dx, other), (ld, 0)], [(dx, 0), (po, 0)]]
    return rf.circuit.Circuit(cnx).network


def branch_noise(saw: rf.Network, dxport: int):
    """Noise factor and transducer gain of one branch (virtual RHCP port -> RF out, 50 ohm)."""
    hyb = cp_hybrid_2port()
    dxr = dxp_2port(dxport)
    ca_lna = M.ca_active(NF_MIN, G_OPT, RN)
    blocks = [(hyb, M.ca_passive(hyb)),
              (CIN, M.ca_passive(CIN)), (LNA, ca_lna), (POST, M.ca_passive(POST)),
              (saw, M.ca_passive(saw)),
              (CIN, M.ca_passive(CIN)), (LNA, ca_lna), (POST, M.ca_passive(POST)),
              (saw, M.ca_passive(saw)),
              (dxr, M.ca_passive(dxr))]
    a, ca = M.cascade_noise(blocks)
    fac = M.noise_factor(ca)
    net = rf.Network(frequency=F, a=a, z0=M.Z0)
    return fac, net, blocks


