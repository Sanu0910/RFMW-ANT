def write_ts(n: rf.Network, fname: str, header: list[str], noise=None):
    n = n.copy()
    n.name = n.name or Path(fname).stem
    n.frequency.unit = "ghz"
    # GHz / real-imaginary: the most widely read form (circuitRF 1.6.1 refuses DB/MHz files)
    txt = n.write_touchstone(return_string=True, form="ri", skrf_comment=False,
                             format_spec_A="{:.7e}", format_spec_B="{:.7e}", format_spec_freq="{:.9g}",
                             write_noise=False)
    lines = ["! " + h for h in header]
    body = txt.splitlines()
    if noise is not None:  # Touchstone v1 noise block: f, NFmin dB, |Gopt|, ang, Rn/Z0
        body.append("! noise parameters: f[GHz] NFmin[dB] |Gopt| ang(Gopt)[deg] Rn/Z0")
        for f, nf, g, rn in zip(*noise):
            body.append(f"{f / 1e9:.6g} {nf:.3f} {abs(g):.3f} {np.rad2deg(np.angle(g)):.2f} {rn / M.Z0:.5f}")
    (TS / fname).write_text("\n".join(lines + body) + "\n", encoding="ascii")


