def main():
    write_component_touchstones()
    sysn = build_system()
    sysn.name = "System_3port"
    write_ts(sysn, "SIM_System_3port.s3p", COMMON + [
        "SIMULATED with scikit-rf (Scripts/simulate.py). Port 1 = L1 virtual RHCP input, port 2 =",
        "L2/L5 virtual RHCP input, port 3 = RF output. LNAs biased, 5 V."])

    nf1, net1, _ = branch_noise(b7("s"), 1)
    nf2, net2, _ = branch_noise(b8("s"), 2)
    g1 = np.abs(net1.s[:, 1, 0]) ** 2
    g2 = np.abs(net2.s[:, 1, 0]) ** 2
    # combined output noise (both branches feed the DXP), referred to each branch's gain
    nf_l1_sys = 10 * np.log10((nf1 * g1 + nf2 * g2) / g1)
    nf_l2_sys = 10 * np.log10((nf1 * g1 + nf2 * g2) / g2)
    write_ts(net1, "SIM_Branch_L1.s2p", COMMON + ["SIMULATED branch: L1 virtual RHCP input -> RF out (L2/L5 port of DXP in 50 ohm)"])
    write_ts(net2, "SIM_Branch_L2L5.s2p", COMMON + ["SIMULATED branch: L2/L5 virtual RHCP input -> RF out (L1 port of DXP in 50 ohm)"])

    s = sysn.s
    res = {"freq_mhz": FM.tolist()}
    k_lna, mu_lna, mu2_lna, d_lna = M.k_mu(M.tqp_table_network())
    k_st, mu_st, _, _ = M.k_mu(STAGE)
    k_b1, mu_b1, _, _ = M.k_mu(net1)
    k_b2, mu_b2, _, _ = M.k_mu(net2)

    # group delay of the system paths
    def gdel(x):
        return -np.gradient(np.unwrap(np.angle(x)), 2 * np.pi * F.f) * 1e9

    gd1, gd2 = gdel(s[:, 2, 0]), gdel(s[:, 2, 1])

    # ---------------- summary at band centres
    summary = []
    for band, (fc, hb, br) in D.GNSS_BANDS.items():
        k = idx(fc)
        sel = (FM >= fc - hb) & (FM <= fc + hb)
        col = 0 if br == "L1" else 1
        g = db(s[:, 2, col])
        nfs = nf_l1_sys if br == "L1" else nf_l2_sys
        gd = gd1 if br == "L1" else gd2
        summary.append(dict(
            band=band, f_mhz=fc, branch="L1" if br == "L1" else "L2/L5",
            gain_db=float(g[k]), gain_ripple_db=float(g[sel].max() - g[sel].min()),
            nf_db=float(nfs[k]), s11_db=float(db(s[k, col, col])), s22_db=float(db(s[k, 2, 2])),
            vswr_in=float((1 + abs(s[k, col, col])) / (1 - abs(s[k, col, col]))),
            vswr_out=float((1 + abs(s[k, 2, 2])) / (1 - abs(s[k, 2, 2]))),
            reverse_iso_db=float(-db(s[k, col, 2])), gd_ns=float(gd[k]),
            gd_ripple_ns=float(gd[sel].max() - gd[sel].min()),
            cross_band_db=float(db(s[k, 2, 1 - col])),
        ))
    res["summary"] = summary

    # ---------------- cascade budgets
    budgets = {
        "L1 C/A (1575.42 MHz, 2.046 MHz)": stage_table("L1", 1575.42, 2.046e6, D.GNSS_MIN_POWER_DBM["L1/E1/B1C"]),
        "L5 (1176.45 MHz, 20.46 MHz)": stage_table("L2", 1176.45, 20.46e6, D.GNSS_MIN_POWER_DBM["L5/E5a/B2a"]),
        "L2C (1227.60 MHz, 2.046 MHz)": stage_table("L2", 1227.60, 2.046e6, D.GNSS_MIN_POWER_DBM["L2"]),
    }
    res["budgets"] = budgets
    res["interferers"] = interferer_table()

    # ---------------- stability summary
    sel = (FM > 600)
    res["stability"] = dict(
        lna_table_k_min=float(k_lna.min()), lna_table_k_min_f_ghz=float(M.tqp_table_network().f[k_lna.argmin()] / 1e9),
        lna_table_mu_min=float(mu_lna.min()), lna_table_delta_max=float(d_lna.max()),
        stage_k_min=float(k_st.min()), stage_mu_min=float(mu_st.min()),
        branch_l1_k_min=float(k_b1[sel].min()), branch_l1_mu_min=float(mu_b1[sel].min()),
        branch_l2_k_min=float(k_b2[sel].min()), branch_l2_mu_min=float(mu_b2[sel].min()))
    res["hc_phase_offsets_deg"] = list(map(float, M.hc125a.phase_offsets_deg))

    # ---------------- validation of models vs datasheet tables
    val = []
    for lo, hi, typ, mx in D.B7504_IL:
        sel = (B7_full.f / 1e6 >= lo) & (B7_full.f / 1e6 <= hi)
        val.append(("B7504 IL %g-%g MHz" % (lo, hi), typ, mx, float(-db(B7_full.s[sel, 1, 0]).mean())))
    for lo, hi, typ, mx in D.B8889_IL:
        sel = (B8_full.f / 1e6 >= lo) & (B8_full.f / 1e6 <= hi)
        val.append(("B8889 IL %g-%g MHz" % (lo, hi), typ, mx, float(-db(B8_full.s[sel, 1, 0]).mean())))
    for lo, hi, mn, typ in D.B7504_ATT:
        sel = (B7_full.f / 1e6 >= lo) & (B7_full.f / 1e6 <= hi)
        val.append(("B7504 att %g-%g MHz (min %g)" % (lo, hi, mn), typ, None, float(-db(B7_full.s[sel, 1, 0]).max())))
    for lo, hi, mn, typ in D.B8889_ATT:
        sel = (B8_full.f / 1e6 >= lo) & (B8_full.f / 1e6 <= hi)
        val.append(("B8889 att %g-%g MHz (min %g)" % (lo, hi, mn), typ, None, float(-db(B8_full.s[sel, 1, 0]).max())))
    sel = (B7_full.f / 1e6 >= 1597.5) & (B7_full.f / 1e6 <= 1605.9)
    g7 = -np.gradient(np.unwrap(np.angle(B7_full.s[:, 1, 0])), 2 * np.pi * B7_full.f) * 1e9
    val.append(("B7504 group-delay ripple 1597.5-1605.9 MHz [ns]", 4.0, 15, float(g7[sel].max() - g7[sel].min())))
    k15 = int(np.argmin(abs(DX_full.f / 1e6 - 1582.19)))
    k12 = int(np.argmin(abs(DX_full.f / 1e6 - 1206.92)))
    val.append(("DXP IL band 1 @1582.19 MHz", 3.8, 4.6, float(-db(DX_full.s[k15, 1, 0]))))
    val.append(("DXP IL band 2 @1206.92 MHz", 4.2, 5.2, float(-db(DX_full.s[k12, 2, 0]))))
    t = M.tqp_table_network()
    k2 = int(np.argmin(abs(t.f - 2.0e9)))
    val.append(("TQP3M9037 gain @2.0 GHz (table) vs spec @1.95", 20.0, 21.5, float(db(t.s[k2, 1, 0]))))
    res["validation"] = [dict(item=a, ds_typ=b, ds_max=c, model=d) for a, b, c, d in val]

    # ---------------- CSV outputs
    import csv
    with open(XD / "results_summary.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(summary[0]))
        w.writeheader(); w.writerows(summary)
    with open(XD / "results_cascade_budget.csv", "w", newline="") as fh:
        keys = ["case"] + list(next(iter(budgets.values()))[0])
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        for case, rows in budgets.items():
            for r in rows:
                w.writerow({"case": case, **r})
    with open(XD / "results_interferers.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(res["interferers"][0]))
        w.writeheader(); w.writerows(res["interferers"])
    with open(XD / "results_validation.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["item", "ds_typ", "ds_max", "model"])
        w.writeheader(); w.writerows(res["validation"])
    np.savetxt(XD / "results_sweep.csv", np.column_stack([
        FM, db(s[:, 2, 0]), db(s[:, 2, 1]), db(s[:, 0, 0]), db(s[:, 1, 1]), db(s[:, 2, 2]),
        db(s[:, 0, 2]), db(s[:, 1, 2]), nf_l1_sys, nf_l2_sys, gd1, gd2,
        np.rad2deg(np.angle(s[:, 2, 0])), np.rad2deg(np.angle(s[:, 2, 1]))]),
        delimiter=",", fmt="%.5g",
        header="f_MHz,S31_dB(L1 gain),S32_dB(L2L5 gain),S11_dB,S22_dB,S33_dB,S13_dB,S23_dB,"
               "NF_L1_dB,NF_L2L5_dB,GD_L1_ns,GD_L2L5_ns,phase_S31_deg,phase_S32_deg", comments="")

    # ---------------- plots
    plots(sysn, net1, net2, nf_l1_sys, nf_l2_sys, gd1, gd2,
          (k_lna, mu_lna, k_st, mu_st, k_b1, mu_b1, k_b2, mu_b2), budgets)
    (ROOT / "Scripts" / "results.json").write_text(json.dumps(
        {k: v for k, v in res.items() if k != "freq_mhz"}, indent=1, default=float))
    return res


def _save(fig, name):
    fig.tight_layout()
    fig.savefig(IMG / name)
    plt.close(fig)


def _lbl(ax, x, y, text, color):
    ax.annotate(text, (x, y), xytext=(4, 4), textcoords="offset points", color=INK, fontsize=8)
    ax.plot([x], [y], "o", ms=4, color=color)


def plots(sysn, net1, net2, nf1, nf2, gd1, gd2, stab, budgets):
    s = sysn.s
    fg = FM / 1e3
    # 1-2: four S-parameters per branch, in-band zoom
    for col, br, lo, hi in ((0, "L1", 1530, 1640), (1, "L2", 1130, 1280)):
        sel = (FM >= lo) & (FM <= hi)
        fig, axs = plt.subplots(2, 2, figsize=(9, 6), sharex=True)
        title = "L1 branch" if br == "L1" else "L2/L5 branch"
        for ax, (i, j, nm, c) in zip(axs.flat, [(col, col, "S11 (input, RHCP port)", C1), (2, col, "S21 (gain)", C1),
                                                 (col, 2, "S12 (reverse isolation)", C2), (2, 2, "S22 (RF output)", C2)]):
            shade(ax, br)
            ax.plot(fg[sel], db(s[sel, i, j]), color=c)
            ax.set_title(f"{title}: {nm}")
            ax.set_ylabel("dB")
        for ax in axs[1]:
            ax.set_xlabel("Frequency (GHz)")
        _save(fig, f"sparams_{br}.png")

    # 3: wideband system transfer
    fig, ax = plt.subplots(figsize=(9, 4))
    ax.plot(fg, db(s[:, 2, 0]), color=C1, label="L1 input -> RF out")
    ax.plot(fg, db(s[:, 2, 1]), color=C2, label="L2/L5 input -> RF out")
    ax.set_ylim(-80, 50)
    ax.set_xlabel("Frequency (GHz)"); ax.set_ylabel("Transducer gain (dB)")
    ax.set_title("System gain, 0.6-2.2 GHz (HC125A held flat outside 1.15-1.63 GHz)")
    ax.legend(loc="lower right")
    _save(fig, "gain_wideband.png")

    # 4: in-band gain both branches
    fig, axs = plt.subplots(1, 2, figsize=(9, 3.6), sharey=True)
    for ax, col, br, lo, hi, c in ((axs[0], 1, "L2", 1150, 1260, C2), (axs[1], 0, "L1", 1550, 1615, C1)):
        sel = (FM >= lo) & (FM <= hi)
        shade(ax, br)
        ax.plot(fg[sel], db(s[sel, 2, col]), color=c)
        ax.set_title(("L2/L5" if br == "L2" else "L1") + " branch gain")
        ax.set_xlabel("Frequency (GHz)")
        for lo_, hi_, lab in BAND_SPANS[br]:
            k = idx((lo_ + hi_) / 2)
            _lbl(ax, fg[k], db(s[k, 2, col]), f"{lab} {db(s[k, 2, col]):.1f} dB", c)
    axs[0].set_ylabel("Gain (dB)")
    axs[0].set_ylim(20, 50)
    _save(fig, "gain_inband.png")

    # 5: noise figure
    fig, axs = plt.subplots(1, 2, figsize=(9, 3.6), sharey=True)
    for ax, nf, br, lo, hi, c in ((axs[0], nf2, "L2", 1150, 1260, C2), (axs[1], nf1, "L1", 1550, 1615, C1)):
        sel = (FM >= lo) & (FM <= hi)
        shade(ax, br)
        ax.plot(fg[sel], nf[sel], color=c, label="System NF (RHCP port)")
        ax.plot(fg[sel], NF_MIN[sel], color=C3, ls="--", label="TQP3M9037 NFmin")
        ax.set_xlabel("Frequency (GHz)")
        ax.set_title(("L2/L5" if br == "L2" else "L1") + " branch noise figure")
    axs[0].set_ylabel("NF (dB)"); axs[0].set_ylim(0, 2.0)
    axs[1].legend(loc="upper center")
    _save(fig, "noise_figure.png")

    # 6: VSWR
    fig, axs = plt.subplots(1, 3, figsize=(9, 3.4), sharey=True)
    vs = lambda g: (1 + np.abs(g)) / (1 - np.abs(g))
    for ax, (i, br, lo, hi, c, t) in zip(axs, [(1, "L2", 1150, 1260, C2, "L2/L5 input (RHCP)"),
                                                (0, "L1", 1550, 1615, C1, "L1 input (RHCP)"),
                                                (2, None, 1150, 1615, C3, "RF output")]):
        sel = (FM >= lo) & (FM <= hi)
        if br:
            shade(ax, br)
        ax.plot(fg[sel], vs(s[sel, i, i]), color=c)
        ax.set_title("VSWR, " + t); ax.set_xlabel("Frequency (GHz)")
    axs[0].set_ylabel("VSWR"); axs[0].set_ylim(1, 4)
    _save(fig, "vswr.png")

    # 7: stability
    k_lna, mu_lna, k_st, mu_st, k_b1, mu_b1, k_b2, mu_b2 = stab
    t = M.tqp_table_network()
    fig, axs = plt.subplots(1, 2, figsize=(9, 3.6))
    axs[0].plot(t.f / 1e9, k_lna, "o-", color=C1, ms=3, label="K, TQP3M9037 (table, 0.05-5 GHz)")
    axs[0].plot(t.f / 1e9, mu_lna, "s-", color=C2, ms=3, label="mu, TQP3M9037")
    axs[0].axhline(1, color=INK2, lw=0.8)
    axs[0].set_xlabel("Frequency (GHz)"); axs[0].set_title("LNA alone: K and mu (>1 = unconditionally stable)")
    axs[0].legend(loc="lower right")
    axs[1].plot(fg, k_st, color=C3, label="K, LNA stage with bias network")
    axs[1].plot(fg, mu_st, color=C4, label="mu, LNA stage")
    axs[1].plot(fg, mu_b1, color=C1, label="mu, L1 branch")
    axs[1].plot(fg, mu_b2, color=C2, label="mu, L2/L5 branch")
    axs[1].axhline(1, color=INK2, lw=0.8)
    axs[1].set_yscale("log"); axs[1].set_xlabel("Frequency (GHz)")
    axs[1].set_title("Stage and branch stability factors")
    axs[1].legend(loc="upper right", fontsize=7)
    _save(fig, "stability.png")

    # 8: group delay; 9: phase
    for kind in ("gd", "phase"):
        fig, axs = plt.subplots(1, 2, figsize=(9, 3.6))
        for ax, col, br, lo, hi, c, g in ((axs[0], 1, "L2", 1160, 1250, C2, gd2), (axs[1], 0, "L1", 1555, 1610, C1, gd1)):
            sel = (FM >= lo) & (FM <= hi)
            shade(ax, br)
            if kind == "gd":
                ax.plot(fg[sel], g[sel], color=c); ax.set_ylabel("Group delay (ns)")
            else:
                ax.plot(fg[sel], np.rad2deg(np.angle(s[sel, 2, col])), color=c); ax.set_ylabel("Phase S21 (deg)")
            ax.set_xlabel("Frequency (GHz)")
            ax.set_title(("L2/L5" if br == "L2" else "L1") + (" group delay [ESTIMATED phase]" if kind == "gd" else " transmission phase"))
        _save(fig, "group_delay.png" if kind == "gd" else "phase.png")

    # 10: component validation overlays
    fig, axs = plt.subplots(2, 2, figsize=(9, 6.4))
    for ax, n, pts, tbl, title, c, rng in (
            (axs[0, 0], B7_full, D.B7504_ATT_DIG, D.B7504_ATT, "B7504 |S21| model vs datasheet", C1, (500, 3000)),
            (axs[0, 1], B8_full, D.B8889_ATT_DIG, D.B8889_ATT, "B8889 |S21| model vs datasheet", C2, (500, 3000))):
        sel = (n.f / 1e6 >= rng[0]) & (n.f / 1e6 <= rng[1])
        ax.plot(n.f[sel] / 1e9, db(n.s[sel, 1, 0]), color=c, label="model (.s2p)")
        p = np.array(pts)
        p = p[(p[:, 0] >= rng[0]) & (p[:, 0] <= rng[1])]
        ax.plot(p[:, 0] / 1e3, -p[:, 1], "o", ms=3, color=INK2, label="digitized points")
        for lo, hi, mn, typ in tbl:
            if lo < rng[1]:
                ax.plot([lo / 1e3, min(hi, rng[1]) / 1e3], [-mn, -mn], color=C4, lw=2)
        ax.plot([], [], color=C4, lw=2, label="spec. min attenuation")
        ax.set_ylim(-90, 5); ax.set_title(title); ax.set_xlabel("Frequency (GHz)"); ax.set_ylabel("dB")
        ax.legend(loc="lower right", fontsize=7)
    fd = DX_full.f / 1e9
    axs[1, 0].plot(fd, db(DX_full.s[:, 1, 0]), color=C1, label="common -> L1")
    axs[1, 0].plot(fd, db(DX_full.s[:, 2, 0]), color=C2, label="common -> L2/L5")
    axs[1, 0].plot(fd, db(DX_full.s[:, 2, 1]), color=C3, label="L1 <-> L2/L5 isolation")
    axs[1, 0].set_ylim(-70, 0); axs[1, 0].set_title("DXP.02.A model"); axs[1, 0].set_xlabel("Frequency (GHz)")
    axs[1, 0].legend(loc="lower right", fontsize=7)
    fh = HC_full.f / 1e9
    sel = (fh >= 1.15) & (fh <= 1.63)
    axs[1, 1].plot(fh[sel], db(HC_full.s[sel, 3, 0]), color=C1, label="pin1->pin4 through")
    axs[1, 1].plot(fh[sel], db(HC_full.s[sel, 2, 0]), color=C2, label="pin1->pin3 coupled")
    tb = np.array(D.HC_TABLE)
    axs[1, 1].plot(tb[:, 0] / 1e3, tb[:, 2], "o", ms=3, color=INK2, label="datasheet table")
    axs[1, 1].plot(tb[:, 0] / 1e3, tb[:, 1], "o", ms=3, color=INK2)
    axs[1, 1].set_ylim(-3.8, -2.9); axs[1, 1].set_title("HC125A model vs table"); axs[1, 1].set_xlabel("Frequency (GHz)")
    axs[1, 1].legend(loc="lower left", fontsize=7)
    _save(fig, "component_models.png")

    # 11: LNA table plot
    fig, ax = plt.subplots(figsize=(9, 3.6))
    for (i, j, nm, c) in [(1, 0, "S21", C1), (0, 0, "S11", C2), (1, 1, "S22", C3), (0, 1, "S12", C4)]:
        ax.plot(t.f / 1e9, db(t.s[:, i, j]), "o-", ms=3, color=c, label=nm)
    ax.set_xlabel("Frequency (GHz)"); ax.set_ylabel("dB")
    ax.set_title("TQP3M9037 S-parameters, 5 V / 70 mA (datasheet table, device leads)")
    ax.legend(loc="center right", ncols=4)
    _save(fig, "lna_sparams.png")

    # 12: level diagram
    fig, axs = plt.subplots(1, 3, figsize=(9.5, 3.8), sharey=True)
    for ax, (case, rows) in zip(axs, budgets.items()):
        x = np.arange(len(rows) + 1)
        sig = [rows[0]["signal_dbm"] - rows[0]["gain_db"]] + [r["signal_dbm"] for r in rows]
        noi = [rows[0]["noise_dbm"] - rows[0]["gain_db"] - rows[0]["cum_nf_db"]] + [r["noise_dbm"] for r in rows]
        ax.step(x, sig, where="post", color=C1, label="signal (min. received)")
        ax.step(x, noi, where="post", color=C2, label="thermal noise in signal BW")
        ax.set_xticks(x, ["ant"] + ["HYB", "LNA1", "SAW1", "LNA2", "SAW2", "DXP"], fontsize=7)
        ax.set_title(case.split(" (")[0], fontsize=9)
    axs[0].set_ylabel("Level (dBm)")
    axs[0].legend(loc="lower right", fontsize=7)
    _save(fig, "level_diagram.png")


