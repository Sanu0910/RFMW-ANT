def lna_large_signal(f_mhz):
    """OIP3 / OP1dB [dBm] interpolated from the 5 V eval table (Qorvo p.6)."""
    fs = sorted(D.TQP_EVAL_5V)
    oip3 = np.interp(f_mhz, fs, [D.TQP_EVAL_5V[f][4] for f in fs])
    op1 = np.interp(f_mhz, fs, [D.TQP_EVAL_5V[f][3] for f in fs])
    return float(oip3), float(op1)


def stage_table(branch, f_mhz, bw_hz, p_sig_dbm):
    k = idx(f_mhz)
    hyb = cp_hybrid_2port()
    saw = b7("s") if branch == "L1" else b8("s")
    dxr = dxp_2port(1 if branch == "L1" else 2)
    lna_nf = 10 * np.log10(M.noise_factor(M.cascade_noise(
        [(CIN, M.ca_passive(CIN)), (LNA, M.ca_active(NF_MIN, G_OPT, RN)), (POST, M.ca_passive(POST))])[1]))[k]
    oip3, op1 = lna_large_signal(f_mhz)
    rows = []
    for name, n, nf in [("HC125A (RHCP combine)", hyb, None), ("LNA1 TQP3M9037 + bias", STAGE, lna_nf),
                        (f"{'B7504' if branch == 'L1' else 'B8889'} #1", saw, None),
                        ("LNA2 TQP3M9037 + bias", STAGE, lna_nf),
                        (f"{'B7504' if branch == 'L1' else 'B8889'} #2", saw, None),
                        ("DXP.02.A (combiner)", dxr, None)]:
        g = float(db(n.s[k, 1, 0]))
        nf_db = float(nf) if nf is not None else -g  # passive at T0, matched: NF = loss
        active = nf is not None
        rows.append(dict(stage=name, gain_db=g, nf_db=nf_db,
                         oip3_dbm=oip3 if active else None, op1db_dbm=op1 if active else None))
    # Friis cascade
    g_lin_cum, f_cum, iip3_inv, ip1_inv = 1.0, 1.0, 0.0, 0.0
    n_floor = 10 * np.log10(k_B * M.T0 * bw_hz * 1e3)
    out = []
    for r in rows:
        g = 10 ** (r["gain_db"] / 10)
        fst = 10 ** (r["nf_db"] / 10)
        f_cum = f_cum + (fst - 1) / g_lin_cum
        if r["oip3_dbm"] is not None:
            iip3_st = r["oip3_dbm"] - r["gain_db"]
            ip1_st = r["op1db_dbm"] - r["gain_db"] + 1
            iip3_inv += 1 / (10 ** (iip3_st / 10) / g_lin_cum)
            ip1_inv += 1 / (10 ** (ip1_st / 10) / g_lin_cum)
        g_lin_cum *= g
        gc = 10 * np.log10(g_lin_cum)
        nfc = 10 * np.log10(f_cum)
        r2 = dict(r)
        r2.update(cum_gain_db=gc, cum_nf_db=nfc,
                  cum_iip3_dbm=(10 * np.log10(1 / iip3_inv) if iip3_inv else None),
                  cum_iip1db_dbm=(10 * np.log10(1 / ip1_inv) if ip1_inv else None),
                  signal_dbm=p_sig_dbm + gc,
                  noise_dbm=n_floor + nfc + gc, snr_db=p_sig_dbm - (n_floor + nfc))
        out.append(r2)
    return out


