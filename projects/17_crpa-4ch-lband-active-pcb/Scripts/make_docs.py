def ind_h(ax, x, y, name, val):
    import numpy as np
    S.w(ax, (x, y), (x + 0.15, y))
    t = np.linspace(0, 4 * np.pi, 200)
    ax.plot(x + 0.15 + 0.7 * t / t[-1], y + 0.13 * np.abs(np.sin(t / 2)), color=S.BODY, lw=1.3, zorder=3)
    S.w(ax, (x + 0.85, y), (x + 1.0, y))
    ax.text(x + 0.5, y + 0.3, name, ha="center", fontsize=7, color=S.NAME)
    ax.text(x + 0.5, y - 0.45, val, ha="center", fontsize=7, color=S.VAL)
    return (x + 1.0, y)


def lna_block(ax, x, y, ref, cin, cout, lch, c3, c4):
    """C in -> TQP3M9037 -> C out with the bias tee drawn above (project 16 LNA sheet, compact)."""
    e = S.cap_h(ax, x, y, cin, "100 pF")
    S.w(ax, e, (x + 1.3, y))
    i, o = S.amp(ax, x + 1.3, y, ref, "TQP3M9037")
    S.w(ax, o, (x + 3.3, y))
    S.dot(ax, x + 3.0, y)
    S.w(ax, (x + 3.0, y), (x + 3.0, y + 0.2))
    import numpy as np
    t = np.linspace(0, 4 * np.pi, 120)
    ax.plot(x + 3.0 + 0.11 * np.abs(np.sin(t / 2)), y + 0.2 + 0.9 * t / t[-1], color=S.BODY, lw=1.2, zorder=3)
    ax.text(x + 3.15, y + 0.75, lch, fontsize=6.3, color=S.NAME)
    ax.text(x + 3.15, y + 0.5, "18 nH", fontsize=6.3, color=S.VAL)
    S.w(ax, (x + 3.0, y + 1.1), (x + 3.0, y + 1.5))
    ax.text(x + 2.2, y + 1.62, f"+5V ({c3} 100p, {c4} 1u)", fontsize=6.0, color="#b35c00")
    e = S.cap_h(ax, x + 3.3, y, cout, "100 pF")
    return e


def saw_block(ax, x, y, ref, part, pin_out):
    p = S.box(ax, x, y, 1.8, 1.0, ref, part, pins_l=["1"], pins_r=[pin_out], pins_b=["GND"])
    S.ground(ax, *p["GND"])
    return p["1"], p[pin_out]


