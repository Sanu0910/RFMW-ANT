def stackup_figure():
    fig, ax = plt.subplots(figsize=(8, 3.6))
    y = 0
    cols = {"copper": "#c8792b", "prepreg": "#9dbb61", "core": "#6e8f3a", "mask": "#2d6a3e"}
    for name, typ, th, er, note in reversed(D.STACKUP):
        if typ == "silk":
            continue
        h = 0.09 if typ in ("copper", "mask") else th
        ax.add_patch(plt.Rectangle((0, y), 4, h, fc=cols[typ], ec="k", lw=0.4))
        lab = f"{name}  {th * 1000:.0f} um" if th < 0.1 else f"{name}  {th:.3f} mm"
        if er:
            lab += f"  er {er}"
        ax.text(4.15, y + h / 2, f"{lab}   {note}", va="center", fontsize=7.5)
        y += h
    ax.text(0, y + 0.06, "4-layer FR-4, 1.6 mm finished (JLC04161H-7628 class).  50 ohm on L4: 0.38 mm over L3, "
            "0.30 mm gap to pour", fontsize=8, fontweight="bold")
    ax.set_xlim(0, 12)
    ax.set_ylim(-0.05, y + 0.2)
    ax.axis("off")
    fig.tight_layout()
    fig.savefig(IMG / "stackup.png", dpi=200)
    plt.close(fig)


