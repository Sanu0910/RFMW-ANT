def ref_key(r):
    import re
    m = re.match(r"([A-Z]+)(\d+)", r)
    return (m.group(1), int(m.group(2))) if m else (r, 0)


def bom():
    groups = OrderedDict()
    for p in PARTS:
        groups.setdefault(p["key"], []).append(p["ref"])
    rows = []
    order = ["HYB", "LIM", "LNA", "SAW_L1", "SAW_L2", "DXP", "L18N", "L6N8", "L4N7", "L3N3", "L4N3",
             "C100P", "C1U", "C1P0", "C1P5", "C10U", "C22U", "C100N", "R50", "R10K", "PTC", "PFET", "TVS",
             "SMA", "JDC", "TP", "CDNP", "ANT"]
    for i, key in enumerate(sorted(groups, key=lambda k: order.index(k) if k in order else 99), 1):
        lib, fp, value, mpn, mfr, desc = D.PARTS[key]
        refs = sorted(groups[key], key=ref_key)
        fit = "DNP" if key == "CDNP" else ("Customer supplied, hand fit (top)" if key == "ANT" else
                                           ("Hand solder (THT)" if key in ("SMA", "JDC") else "SMT bottom"))
        rows.append(dict(Item=i, Qty=len(refs), References=" ".join(refs), Value=value, MPN=mpn,
                         Manufacturer=mfr, Footprint=f"{lib}:{fp}", Description=desc, Fit=fit))
    with open(FAB / "CRPA17_4CH_LBAND_BOM.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Font, PatternFill, Alignment
        wb = Workbook()
        ws = wb.active
        ws.title = "BOM"
        ws.append(list(rows[0]))
        for c in ws[1]:
            c.font = Font(bold=True, color="FFFFFF")
            c.fill = PatternFill("solid", fgColor="1F3A5F")
        for r in rows:
            ws.append(list(r.values()))
        for col, wd in zip("ABCDEFGHI", (6, 5, 60, 14, 22, 16, 48, 52, 30)):
            ws.column_dimensions[col].width = wd
        for row in ws.iter_rows(min_row=2):
            row[2].alignment = Alignment(wrap_text=True, vertical="top")
        wb.save(FAB / "CRPA17_4CH_LBAND_BOM.xlsx")
    except ImportError:
        pass
    return rows


def netlist():
    rows = []
    for p in PARTS:
        for pin, net in sorted(p["nets"].items()):
            if net:
                rows.append((net, p["ref"], pin))
    rows.sort(key=lambda r: (r[0], ref_key(r[1]), r[2]))
    with open(DOCS / "CRPA17_netlist.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["net", "ref", "pin"])
        w.writerows(rows)
    return rows


# ----------------------------------------------------------------------------- RF budget
LOSS_DB_PER_MM = 0.0082        # 0.38 mm 50-ohm line on 0.21 mm 7628 FR-4, tan d 0.02, 1.2-1.6 GHz (skrf)
# RLM-63-2W+ insertion loss in the linear range (data sheet table, +3 dBm): 1040 MHz 0.09, 1520 MHz 0.15,
# 2000 MHz 0.15 dB. Linear interpolation inside the GNSS bands.
LIM_IL = [(1040, 0.09), (1520, 0.15), (2000, 0.15)]


def lim_il(f):
    for (f0, a0), (f1, a1) in zip(LIM_IL[:-1], LIM_IL[1:]):
        if f0 <= f <= f1:
            return a0 + (a1 - a0) * (f - f0) / (f1 - f0)
    return LIM_IL[-1][1]


def budget():
    src = P16 / "Extracted_Data" / "results_cascade_budget.csv"
    cases = OrderedDict()
    with open(src) as f:
        for r in csv.DictReader(f):
            cases.setdefault(r["case"], []).append(r)
    ch = "CH1"
    out, summary = [], []
    for case, stages in cases.items():
        band = "L1" if case.startswith("L1") else "L2"
        fmhz = float(case.split("(")[1].split(" MHz")[0])
        feed = (NETLEN[f"{ch}_{band}_F0"] + NETLEN[f"{ch}_{band}_F90"]) / 2
        hyb_lim = NETLEN[f"{ch}_{band}_HYB"]
        lim_lna = NETLEN[f"{ch}_{band}_LIM"] + NETLEN[f"{ch}_{band}_A1IN"]
        st = [("Feed line, patch pin -> hybrid", -feed * LOSS_DB_PER_MM, feed * LOSS_DB_PER_MM)]
        for r in stages:
            g, nf = float(r["gain_db"]), float(r["nf_db"])
            st.append((r["stage"], g, nf))
            if r["stage"] in ("B7504 #2", "B8889 #2"):          # Rev B: third SAW, same part
                st.append((r["stage"].replace("#2", "#3 (Rev B)"), g, nf))
            if r["stage"].startswith("HC125A"):
                st.append(("Line, hybrid -> limiter", -hyb_lim * LOSS_DB_PER_MM, hyb_lim * LOSS_DB_PER_MM))
                il = lim_il(fmhz)
                st.append(("RLM-63-2W+ limiter", -il, il))
                st.append(("Line, limiter -> LNA1", -lim_lna * LOSS_DB_PER_MM, lim_lna * LOSS_DB_PER_MM))
        cg, cf = 0.0, 1.0     # cumulative gain (dB), noise factor
        gl = 1.0
        for name, g, nf in st:
            F = 10 ** (nf / 10)
            cf += (F - 1) / gl
            gl *= 10 ** (g / 10)
            cg += g
            out.append(dict(case=case, stage=name, gain_db=round(g, 3), nf_db=round(nf, 3),
                            cum_gain_db=round(cg, 2), cum_nf_db=round(10 * math.log10(cf), 3)))
        p16_nf = float(stages[-1]["cum_nf_db"])
        p16_g = float(stages[-1]["cum_gain_db"])
        summary.append(dict(case=case, f_mhz=fmhz, gain_p16=round(p16_g, 2), nf_p16=round(p16_nf, 3),
                            gain_p17=round(cg, 2), nf_p17=round(10 * math.log10(cf), 3),
                            d_nf=round(10 * math.log10(cf) - p16_nf, 3), lim_il=round(lim_il(fmhz), 3),
                            pre_lna_line_mm=round(feed + hyb_lim + lim_lna, 2)))
    with open(DOCS / "rf_budget_stages.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0]))
        w.writeheader()
        w.writerows(out)
    with open(DOCS / "rf_budget_summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(summary[0]))
        w.writeheader()
        w.writerows(summary)
    return summary


def power_budget():
    i_typ = D.N_LNA * D.IDD_TYP
    i_max = D.N_LNA * D.IDD_MAX
    r_path = 0.070 + 0.050 + 0.010       # PTC (MF-MSMF200 R1max ~0.07), AO3401A Rds(on) ~0.05, copper
    return dict(n_lna=D.N_LNA, i_typ=i_typ, i_max=i_max, p_typ=i_typ * D.VDD, drop_typ=i_typ * r_path,
                drop_max=i_max * r_path, per_channel=4 * D.IDD_TYP)


